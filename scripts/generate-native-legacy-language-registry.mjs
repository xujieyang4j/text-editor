import assert from "node:assert/strict"
import { createHash } from "node:crypto"
import { readFile, writeFile } from "node:fs/promises"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { StreamLanguage } from "@codemirror/language"
import { languages } from "@codemirror/language-data"

const LANGUAGE_DATA_VERSION = "6.5.2"
const LEGACY_MODES_VERSION = "6.5.3"
const EXPECTED_LANGUAGE_COUNT = 143
const EXPECTED_MODERN_COUNT = 33
const EXPECTED_STREAM_COUNT = 110
const EXPECTED_ALIAS_COUNT = 184
const EXPECTED_UNIQUE_ALIAS_COUNT = 182
const EXPECTED_LEGACY_MODULE_COUNT = 94
const EXPECTED_SOURCE_SHA256 =
  "7f0fbdebcd178f321465ee544284e35b3f93a3d9b6c10999e5d81e2500b0b56b"
const EXPECTED_NAMES_SHA256 =
  "03c720db1a91ad17ef764095403ba9146daab7b7ba23bf69607d6ff4a2e84df0"
const EXPECTED_METADATA_SHA256 =
  "8d80db26f5a076b80aa03e217937454627e0e3a1814c9f0ee63f861757749654"
const EXPECTED_FULL_METADATA_SHA256 =
  "ed840b94abeefe87aa177521a79f1fbe4d85088b6de06cf548885f200aca5c80"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const languageDataRoot = join(root, "node_modules/@codemirror/language-data")
const legacyModesRoot = join(root, "node_modules/@codemirror/legacy-modes")
const upstream = join(languageDataRoot, "dist/index.js")
const output = join(
  root, "native-macos/ParserBundle/LegacyLanguageRegistry.generated.js"
)
const windowsOutput = join(
  root, "native-windows/src/LumenEditor.Windows.Core/Documents/LanguageCatalog.Generated.cs"
)
const checking = process.argv.includes("--check")

function sha256(value) {
  return createHash("sha256").update(value).digest("hex")
}

async function readPackageVersion(directory) {
  return JSON.parse(await readFile(join(directory, "package.json"), "utf8")).version
}

function languageBlocks(source) {
  const marker = "/*@__PURE__*/LanguageDescription.of({"
  return source.split(marker).slice(1).map((chunk, index) => {
    const commaEnd = chunk.indexOf("\n    }),")
    const end = commaEnd === -1 ? chunk.indexOf("\n    })\n];") : commaEnd
    assert.notEqual(end, -1, `Cannot find the end of language block ${index}`)
    return chunk.slice(0, end)
  })
}

function parseJSONStringField(block, field) {
  const match = new RegExp(
    `(?:^|\\n)\\s*${field}: (\"(?:[^\"\\\\]|\\\\.)*\")`
  ).exec(block)
  assert.ok(match, `Language block has no ${field}`)
  return JSON.parse(match[1])
}

function parseLegacyLoad(block) {
  const match = /return import\('(@codemirror\/legacy-modes\/mode\/[^']+)'\)\.then\(m => legacy\(m\.([A-Za-z_$][\w$]*)(\(\{\}\))?\)\);/.exec(block)
  if (!match) return null
  return { module: match[1], exportName: match[2], factory: Boolean(match[3]) }
}

function renderRegistry(descriptors, legacyLoads) {
  const bindings = new Map()
  for (const load of legacyLoads.values()) {
    const key = `${load.module}\0${load.exportName}`
    if (!bindings.has(key)) bindings.set(key, `legacyParser${bindings.size}`)
  }
  const modules = new Map()
  for (const [key, binding] of bindings) {
    const [module, exportName] = key.split("\0")
    if (!modules.has(module)) modules.set(module, [])
    modules.get(module).push({ exportName, binding })
  }
  const lines = [
    "/* Generated by scripts/generate-native-legacy-language-registry.mjs. Do not edit. */"
  ]
  for (const [module, imports] of modules) {
    const names = imports.map(({ exportName, binding }) =>
      `${exportName} as ${binding}`)
    lines.push(`import { ${names.join(", ")} } from ${JSON.stringify(module)}`)
  }
  lines.push(
    "",
    `export const LANGUAGE_DATA_VERSION = ${JSON.stringify(LANGUAGE_DATA_VERSION)}`,
    "",
    "export const LANGUAGE_DESCRIPTORS = Object.freeze(["
  )
  for (const descriptor of descriptors) {
    const kind = legacyLoads.has(descriptor.name) ? "stream" : "lezer"
    lines.push(
      `  Object.freeze({ name: ${JSON.stringify(descriptor.name)}, aliases: Object.freeze(${JSON.stringify(descriptor.alias)}), parserKind: ${JSON.stringify(kind)} }),`
    )
  }
  lines.push(
    "])",
    "",
    "export const LEGACY_LANGUAGE_PARSERS = new Map(["
  )
  for (const descriptor of descriptors) {
    const load = legacyLoads.get(descriptor.name)
    if (!load) continue
    const binding = bindings.get(`${load.module}\0${load.exportName}`)
    const value = load.factory ? `${binding}({})` : binding
    lines.push(`  [${JSON.stringify(descriptor.name)}, ${value}],`)
  }
  lines.push("])", "")
  return lines.join("\n")
}

function languageID(name) {
  const special = new Map([
    ["C++", "cpp"], ["C#", "csharp"], ["F#", "fsharp"],
    ["Objective-C++", "objective-cpp"], ["VB.NET", "vbnet"],
    ["Xù", "xu"]
  ])
  return special.get(name) ?? name.normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "").toLowerCase()
    .replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")
}

function csharpString(value) {
  return JSON.stringify(value).replace(/\u2028|\u2029/g, character =>
    `\\u${character.charCodeAt(0).toString(16).padStart(4, "0")}`)
}

function renderWindowsCatalog(descriptors) {
  const ids = new Set()
  const lines = [
    "// Generated by scripts/generate-native-legacy-language-registry.mjs. Do not edit.",
    "namespace LumenEditor.Windows.Core.Documents;",
    "",
    "internal static class GeneratedLanguageCatalog",
    "{",
    "    public static readonly IReadOnlyList<LanguageDefinition> All =",
    "    [",
    "        new(\"plain\", \"Plain Text\", \"plain\", [], [], null, false),"
  ]
  for (const descriptor of descriptors) {
    const id = languageID(descriptor.name)
    assert.ok(id && !ids.has(id), `Generated Windows language ID is invalid or duplicated: ${id}`)
    ids.add(id)
    const aliases = descriptor.alias.map(csharpString).join(", ")
    const extensions = descriptor.extensions.map(extension =>
      csharpString(`.${extension}`)).join(", ")
    const filename = descriptor.filename ? csharpString(descriptor.filename.source) : "null"
    const ignoreCase = descriptor.filename?.ignoreCase ? "true" : "false"
    lines.push(
      `        new(${csharpString(id)}, ${csharpString(descriptor.name)}, `
        + `${csharpString(descriptor.name)}, [${aliases}], [${extensions}], `
        + `${filename}, ${ignoreCase}),`
    )
  }
  lines.push("    ];", "}", "")
  return lines.join("\n")
}

async function generate() {
  assert.equal(
    await readPackageVersion(languageDataRoot), LANGUAGE_DATA_VERSION,
    `@codemirror/language-data must be exactly ${LANGUAGE_DATA_VERSION}`
  )
  assert.equal(
    await readPackageVersion(legacyModesRoot), LEGACY_MODES_VERSION,
    `@codemirror/legacy-modes must be exactly ${LEGACY_MODES_VERSION}`
  )

  const source = await readFile(upstream, "utf8")
  assert.equal(sha256(source), EXPECTED_SOURCE_SHA256,
    "language-data dist source changed; audit its loaders before updating the generator")
  const blocks = languageBlocks(source)
  assert.equal(blocks.length, EXPECTED_LANGUAGE_COUNT)

  const parsedNames = blocks.map(block => parseJSONStringField(block, "name"))
  const names = languages.map(descriptor => descriptor.name)
  assert.deepEqual(parsedNames, names, "dist source and exported descriptors disagree")
  assert.equal(languages.length, EXPECTED_LANGUAGE_COUNT)
  assert.equal(sha256(JSON.stringify(names)), EXPECTED_NAMES_SHA256,
    "language-data canonical language set changed")
  assert.equal(
    sha256(JSON.stringify(languages.map(({ name, alias }) => [name, alias]))),
    EXPECTED_METADATA_SHA256, "language-data canonical/alias metadata changed"
  )
  assert.equal(sha256(JSON.stringify(languages.map(
    ({ name, alias, extensions, filename }) =>
      [name, alias, extensions, filename?.source ?? null, filename?.flags ?? ""]
  ))), EXPECTED_FULL_METADATA_SHA256,
  "language-data full detection metadata changed")
  const aliases = languages.flatMap(descriptor => descriptor.alias)
  assert.equal(aliases.length, EXPECTED_ALIAS_COUNT)
  assert.equal(new Set(aliases).size, EXPECTED_UNIQUE_ALIAS_COUNT)

  const legacyLoads = new Map()
  for (const block of blocks) {
    const name = parseJSONStringField(block, "name")
    const load = parseLegacyLoad(block)
    if (load) legacyLoads.set(name, load)
    else assert.ok(!block.includes("@codemirror/legacy-modes"),
      `Unrecognized legacy loader syntax for ${name}`)
  }
  assert.equal(legacyLoads.size, EXPECTED_STREAM_COUNT)
  assert.equal(
    new Set(Array.from(legacyLoads.values(), load => load.module)).size,
    EXPECTED_LEGACY_MODULE_COUNT
  )
  assert.deepEqual(
    Array.from(legacyLoads.keys()).filter(name => legacyLoads.get(name).factory),
    ["ASN.1"], "ASN.1 must remain the only legacy parser factory"
  )

  const supports = await Promise.all(languages.map(descriptor => descriptor.load()))
  const streamNames = languages.filter((_, index) =>
    supports[index].language instanceof StreamLanguage
  ).map(descriptor => descriptor.name)
  assert.equal(streamNames.length, EXPECTED_STREAM_COUNT)
  assert.equal(languages.length - streamNames.length, EXPECTED_MODERN_COUNT)
  assert.deepEqual(streamNames, Array.from(legacyLoads.keys()),
    "Parsed legacy loaders disagree with actual StreamLanguage loads")

  const loadedModules = new Map()
  for (const [name, load] of legacyLoads) {
    if (!loadedModules.has(load.module)) {
      loadedModules.set(load.module, await import(load.module))
    }
    const module = loadedModules.get(load.module)
    assert.ok(Object.hasOwn(module, load.exportName),
      `${load.module} does not export ${load.exportName} for ${name}`)
    const exported = module[load.exportName]
    if (load.factory) {
      assert.equal(typeof exported, "function", `${name} export is not a factory`)
    } else {
      assert.equal(typeof exported, "object", `${name} export is not a parser object`)
    }
    const parser = load.factory ? exported({}) : exported
    assert.ok(parser && (parser.startState == null || typeof parser.startState === "function"),
      `${name} parser has an invalid startState`)
    assert.equal(typeof parser?.token, "function", `${name} parser has no token`)
    const index = names.indexOf(name)
    const actual = supports[index].language.streamParser
    if (parser.name != null) {
      assert.equal(actual.name, parser.name, `${name} actual loader uses a different parser`)
    }
    if (!load.factory) {
      assert.equal(actual.token, parser.token, `${name} actual loader uses a different export`)
    }
  }
  return {
    parserRegistry: renderRegistry(languages, legacyLoads),
    windowsCatalog: renderWindowsCatalog(languages)
  }
}

const generated = await generate()
if (checking) {
  let committed
  try {
    committed = await readFile(output, "utf8")
  } catch {
    throw new Error("Legacy language registry is missing; run npm run build:native-parser")
  }
  assert.equal(committed, generated.parserRegistry,
    "Legacy language registry is stale; run npm run build:native-parser")
  let committedWindows
  try {
    committedWindows = await readFile(windowsOutput, "utf8")
  } catch {
    throw new Error("Windows language catalog is missing; run npm run build:native-parser")
  }
  assert.equal(committedWindows, generated.windowsCatalog,
    "Windows language catalog is stale; run npm run build:native-parser")
  process.stdout.write("Native language catalogs are current (143 languages, 110 stream modes).\n")
} else {
  await writeFile(output, generated.parserRegistry)
  await writeFile(windowsOutput, generated.windowsCatalog)
  process.stdout.write(
    `Generated native language catalogs (143 languages, 110 stream modes).\n`
  )
}
